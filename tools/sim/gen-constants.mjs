// Generate tools/sim/stubs/constants.mjs from the vendored API reference.
//
// Hand-maintaining this file bit the simulator once already: a missing
// SPAWN_RANGE made `spawnCreep` ignore every extension, so neither side could
// afford a fighter and every match looked identical. Deriving it from the docs
// the client ships means the simulator cannot quietly disagree with the game.
//
// Usage: node tools/sim/gen-constants.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const DOC = 'docs/api/Constants.md';
const OUT = 'tools/sim/stubs/constants.mjs';

const text = readFileSync(DOC, 'utf8');

/** Rows look like: | `NAME` | `VALUE` | — with VALUE occasionally empty. */
function rows(section) {
  const body = section.split('\n').filter(line => line.startsWith('|'));
  const out = [];
  for (const line of body) {
    const match = line.match(/^\|\s*`([^`]+)`\s*\|\s*`?([^`|]*)`?\s*\|/);
    if (!match) continue;
    out.push([match[1].trim(), match[2].trim()]);
  }
  return out;
}

/** Turn a documented value into a JavaScript expression. */
function literal(raw) {
  if (raw === '') return '[]'; // only OBSTACLE_OBJECT_TYPES, which is a list
  if (/^-?\d+(\.\d+)?$/.test(raw)) return raw;
  if (raw.startsWith('{')) {
    // e.g. {0: 1, 1: 1, 2: 0.4, 3: 0.1}
    return `{ ${raw
      .slice(1, -1)
      .split(',')
      .map(pair => {
        const [key, value] = pair.split(':').map(s => s.trim());
        return `${key}: ${value}`;
      })
      .join(', ')} }`;
  }
  // e.g. [RESOURCE_ENERGY] — a list of other constants, emitted as references.
  if (raw.startsWith('[')) return raw;
  return JSON.stringify(raw);
}

const sections = text.split(/\n## /);
const main = sections[0];
const named = Object.fromEntries(sections.slice(1).map(part => [part.split('\n')[0].trim(), part]));

const lines = [
  '// GENERATED by tools/sim/gen-constants.mjs from docs/api/Constants.md.',
  '// Do not edit by hand — run `bin/arena sim` or the generator directly.',
  '',
];

const scalars = [];
const composites = [];
for (const [name, raw] of rows(main)) {
  const target = raw.startsWith('[') ? composites : scalars;
  target.push(`export const ${name} = ${literal(raw)};`);
}
lines.push(...scalars, '', ...composites);

// BODYPART_COST is keyed by the body-part constants themselves.
if (named.BODYPART_COST) {
  const entries = rows(named.BODYPART_COST).map(([key, value]) => {
    const part = key.replace(/^\[|\]$/g, '');
    return `  [${part}]: ${value},`;
  });
  lines.push('', 'export const BODYPART_COST = {', ...entries, '};');
}

// CONSTRUCTION_COST is keyed by structure name.
if (named.CONSTRUCTION_COST) {
  const entries = rows(named.CONSTRUCTION_COST).map(([key, value]) => `  ${key}: ${value},`);
  lines.push('', 'export const CONSTRUCTION_COST = {', ...entries, '};');
}

writeFileSync(OUT, `${lines.join('\n')}\n`);
console.log(`wrote ${OUT} (${scalars.length + composites.length} constants)`);
