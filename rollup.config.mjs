import { existsSync, mkdirSync, readdirSync, statSync, copyFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import typescript from '@rollup/plugin-typescript';

const ARENAS_SRC = 'src/arenas';

const ROOT = path.dirname(fileURLToPath(import.meta.url));

/**
 * Where the client reads each arena's script from. It is told which folder to
 * use, and writes its own jsconfig.json and typings/ into it; builds deploy
 * `<gameDir>/<arena-name>/main.mjs` alongside those. Kept inside the repo rather
 * than under $HOME so the whole project travels together — the contents are
 * generated, and game/.gitignore keeps them out of git. Override with
 * ARENA_GAME_DIR.
 */
const GAME_DIR = process.env.ARENA_GAME_DIR || path.join(ROOT, 'game');

/**
 * Only build arenas matching this substring. Passed as an environment variable
 * rather than a CLI flag because rollup's own argument parser eats anything it
 * does not recognise (`-c --` reads the next token as a config path).
 */
const filter = process.env.ARENA_FILTER ?? '';

const banner = '// Generated by rollup. Edit the TypeScript in src/, never this file.\n';

/** Copy the built bundle into the client's folder so the game picks it up live. */
function deployToClient(arena) {
  return {
    name: 'deploy-to-client',
    writeBundle(options) {
      const built = path.join(options.dir, 'main.mjs');
      const target = path.join(GAME_DIR, arena);
      if (!existsSync(target)) {
        this.warn(
          `no client folder at ${target} — open "${arena}" in Screeps Arena once ` +
            `(it creates the folder), then rebuild.`,
        );
        return;
      }
      mkdirSync(target, { recursive: true });
      copyFileSync(built, path.join(target, 'main.mjs'));
      console.log(`  → deployed ${arena} to ${path.join(target, 'main.mjs')}`);
    },
  };
}

const arenas = existsSync(ARENAS_SRC)
  ? readdirSync(ARENAS_SRC)
      .filter(name => statSync(path.join(ARENAS_SRC, name)).isDirectory())
      .filter(name => name.includes(filter))
  : [];

if (arenas.length === 0) {
  throw new Error(
    filter
      ? `No arena in ${ARENAS_SRC}/ matches "${filter}".`
      : `No arenas found. Create one with: bin/arena new <arena-name>`,
  );
}

console.log(`Building ${arenas.length} arena(s): ${arenas.join(', ')}`);

export default arenas.map(arena => ({
  input: `${ARENAS_SRC}/${arena}/main.ts`,
  output: {
    dir: `dist/${arena}`,
    format: 'esm',
    entryFileNames: 'main.mjs',
    sourcemap: false,
    banner,
    // The sandbox loads one file per arena; keep everything inlined.
    inlineDynamicImports: true,
  },
  // `game/*` modules are provided by the runtime as bare specifiers.
  external: id =>
    id === 'game' || id.startsWith('game/') || id === 'arena' || id.startsWith('arena/'),
  plugins: [
    typescript({
      tsconfig: './tsconfig.json',
      noEmit: false,
      outDir: `dist/${arena}`,
      // Each arena is its own program rooted at src/.
      include: ['src/**/*.ts', 'typings/**/*.d.ts'],
    }),
    deployToClient(arena),
  ],
  // The game reports errors poorly; surface everything at build time instead.
  onwarn(warning, warn) {
    if (warning.code === 'UNRESOLVED_IMPORT') throw new Error(warning.message);
    warn(warning);
  },
}));
